-- 6) 守卫查询
--    6.1 应输出 10 行，状态分布 未办理2 / 办理中2 / 已办结4 / 已归档2
-- ---------------------------------------------------------------------------
SELECT `status` AS 办理状态, COUNT(*) AS 项目数,
       SUM(`material_count`) AS 材料数, SUM(`record_count`) AS 意见数
FROM `t_escalation_project`
WHERE `id` LIKE 'demo-ep-%'
GROUP BY `status`
ORDER BY FIELD(`status`, '未办理', '办理中', '已办结', '已归档');

--    6.2 应输出 5 行（含 1 行空值），验证 5 种论证结果都覆盖到
SELECT IFNULL(`arg_result`, '（空）') AS 论证结果, COUNT(*) AS 项目数
FROM `t_escalation_project`
WHERE `id` LIKE 'demo-ep-%'
GROUP BY `arg_result`
ORDER BY `arg_result`;

--    6.3 应输出 0 行：冗余计数与子表实际条数不一致的项目
SELECT p.`id`, p.`project_no`, p.`material_count`,
       (SELECT COUNT(*) FROM `t_escalation_material` m WHERE m.`project_id` = p.`id` AND m.`del_flag` = 0) AS 实际材料数,
       p.`record_count`,
       (SELECT COUNT(*) FROM `t_escalation_record` r WHERE r.`project_id` = p.`id`) AS 实际意见数
FROM `t_escalation_project` p
WHERE p.`id` LIKE 'demo-ep-%'
  AND (p.`material_count` <> (SELECT COUNT(*) FROM `t_escalation_material` m WHERE m.`project_id` = p.`id` AND m.`del_flag` = 0)
    OR p.`record_count`   <> (SELECT COUNT(*) FROM `t_escalation_record` r WHERE r.`project_id` = p.`id`));

