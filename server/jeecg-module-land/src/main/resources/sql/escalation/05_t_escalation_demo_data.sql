UPDATE `t_escalation_project` p
LEFT JOIN (
    SELECT `project_id`, COUNT(*) AS cnt
      FROM `t_escalation_material`
     WHERE `del_flag` = 0 AND `project_id` LIKE 'demo-ep-%'
     GROUP BY `project_id`
) m ON m.`project_id` = p.`id`
LEFT JOIN (
    SELECT `project_id`, COUNT(*) AS cnt
      FROM `t_escalation_record`
     WHERE `project_id` LIKE 'demo-ep-%'
     GROUP BY `project_id`
) r ON r.`project_id` = p.`id`
SET p.`material_count`      = IFNULL(m.cnt, 0),
    p.`record_count`        = IFNULL(r.cnt, 0),
    p.`latest_opinion_time` = (SELECT MAX(x.`record_time`) FROM `t_escalation_record` x WHERE x.`project_id` = p.`id`),
    p.`latest_opinion_by`   = (SELECT x.`recorder_name` FROM `t_escalation_record` x
                                WHERE x.`project_id` = p.`id` ORDER BY x.`record_time` DESC, x.`id` DESC LIMIT 1),
    p.`latest_opinion`      = (SELECT LEFT(x.`opinion`, 200) FROM `t_escalation_record` x
                                WHERE x.`project_id` = p.`id` AND x.`opinion` IS NOT NULL
                                ORDER BY x.`record_time` DESC, x.`id` DESC LIMIT 1)
WHERE p.`id` LIKE 'demo-ep-%';

