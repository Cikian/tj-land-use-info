-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `t_process_configuration` (
  `id`            varchar(64)   NOT NULL                COMMENT '主键（沿用旧库 process_configuration.id）',
  `name`          varchar(100)      NULL                COMMENT '环节名称',
