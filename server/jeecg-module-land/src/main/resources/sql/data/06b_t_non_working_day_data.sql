--  ★ 为什么需要这份数据：
--    t_non_working_day 是从旧库 nutzwk_ywk 迁来的，而旧表 116 行**只覆盖 2023 年**；
--    目标库（腾讯-北京）甚至只有 tj-jyxyd、没有旧库，实测该表 0 行。
--    表为空时 WorkdayCalculator 会退化为「只剔周六日 + 内置法定节假日估算」，
--    后果是每年春节与国庆前后，环节的「预计结束时间」系统性偏早，
--    中心在逾期预警里会看到一批其实还没到期的环节。
--
--  ★★ 踩坑记录（这份脚本第一版就是这么错的，务必注意）：
--    第一版用「数字序列 0~99 天」来生成节假日（`a.n + b.n*10` 只能到 99），
--    结果**每年 4 月 6 日之后的节假日全部被静默丢掉**：
--    执行后每年仍有 ~113 行（周末够多，看起来「有数据」）、
--    年份覆盖也显示正常，但 2026 年 10 月的国庆长假一行都没有 ——
--    于是「国庆后第 1 个工作日」被算成 10-02（长假中间）。
--    这一类 bug 的特征是**表面上完全正常**：行数、年份、周末数全对，只有个别区间缺失。
--    所以本版改成：
--      · 周末 → 用 0~3999 的数字序列（四个 0~9 交叉连接，足够覆盖 10 年）；
--      · 法定节假日 → **定值逐条列出**（每年就十来条，写清楚比生成更可靠）；
--      · 末尾加「每个年份的法定节假日区间是否完整」的核对查询。
--
--  ★ 口径：week_end = '1' 周末 / '2' 法定节假日。
--    调休上班的周六**不登记**（与旧系统口径一致；如需精确到调休，把那些周六删掉即可）。
--
--  ★★ 数据来源与时效性（务必让中心按年核对）：
--    下面的法定节假日日期是**按国务院放假安排的估算**，不是权威数据。
--    权威安排每年 11~12 月才公布次年，届时中心只需增删本表行，
--    **代码无需改动**（WorkdayCalculator 优先读本表）。
--    未维护的年份，服务层会返回 calendarBased=false，前端据此提示
--    「按周末 + 内置法定节假日估算」。
--
--  可重复执行：先按 'nwd-' 前缀清理本脚本生成的行，再重新生成。
-- ============================================================================

SET NAMES utf8mb4;

DELETE FROM `t_non_working_day` WHERE `id` LIKE 'nwd-%';

-- ---------------------------------------------------------------------------
-- 1) 2025-01-01 ~ 2027-12-31 的全部周六日
--    数字序列 0~3999（a/b/c/d 四张 0~9 的单列表交叉连接），
--    足够覆盖 1095 天，且不像初版那样只能到 99 天。
-- ---------------------------------------------------------------------------
INSERT INTO `t_non_working_day`
  (`id`, `non_working_time`, `non_working_string`, `non_working_china`, `week_end`, `week_end_china`,
   `create_by`, `create_time`)
SELECT CONCAT('nwd-', DATE_FORMAT(d.dt, '%Y%m%d')), d.dt, DATE_FORMAT(d.dt, '%Y%m%d'),
       DATE_FORMAT(d.dt, '%Y年%m月%d日'), '1', '周末', 'admin', NOW()
FROM (
  SELECT DATE_ADD('2025-01-01', INTERVAL seq DAY) AS dt
  FROM (
    SELECT a.n + b.n * 10 + c.n * 100 + d.n * 1000 AS seq
    FROM (SELECT 0 n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
          UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) a
    CROSS JOIN (SELECT 0 n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
          UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) b
    CROSS JOIN (SELECT 0 n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
          UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) c
    CROSS JOIN (SELECT 0 n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3) d
  ) seqs
  WHERE DATE_ADD('2025-01-01', INTERVAL seq DAY) <= '2027-12-31'
) d
WHERE DAYOFWEEK(d.dt) IN (1, 7);

