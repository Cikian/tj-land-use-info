-- ---------------------------------------------------------------------------
-- 3) 核对 1：每年的非工作日天数应在 110~135 之间
--    （104 个周末 + 11~19 个法定节假日；2027 年因中秋与国庆相邻会到 126 左右，
--      所以上限给 135 —— 定太紧会把正常年份报成异常，反而没人看告警）
-- ---------------------------------------------------------------------------
SELECT YEAR(`non_working_time`) AS 年份, COUNT(*) AS 非工作日天数,
       SUM(CASE WHEN `week_end` = '1' THEN 1 ELSE 0 END) AS 周末,
       SUM(CASE WHEN `week_end` = '2' THEN 1 ELSE 0 END) AS 法定节假日,
       CASE WHEN COUNT(*) BETWEEN 110 AND 135 THEN '正常' ELSE '★异常' END AS 判定
FROM `t_non_working_day`
GROUP BY YEAR(`non_working_time`) ORDER BY 年份;

-- ---------------------------------------------------------------------------
-- 4) ★★ 核对 2：**国庆长假必须存在** —— 这是初版翻车的地方
--
--    初版生成节假日时只数到「年内第 99 天」，于是**每年 4 月 6 日之后的节假日
--    全部被静默丢掉**。当时行数（~113）、年份覆盖、周末数全都正常，
--    只有国庆这一整段缺了 —— 表现成「国庆后第 1 个工作日」被算成长假中间的
--    10-02。这类「表面正常、个别区间缺失」的问题最难靠肉眼发现，
--    所以这里专门盯住国庆：应输出 3 行，且每行都是 8 天。
-- ---------------------------------------------------------------------------
SELECT y.`年份`, '国庆(10/1-10/8)' AS 假期,
       COUNT(n.`id`) AS 非工作日天数,
       CASE WHEN COUNT(n.`id`) = 8 THEN '正常' ELSE '★缺失，必须修正' END AS 判定
FROM (SELECT 2025 AS `年份` UNION SELECT 2026 UNION SELECT 2027) y
LEFT JOIN `t_non_working_day` n
       ON YEAR(n.`non_working_time`) = y.`年份`
      AND n.`non_working_time` BETWEEN CONCAT(y.`年份`, '-10-01') AND CONCAT(y.`年份`, '-10-08')
GROUP BY y.`年份` ORDER BY 年份;

-- ---------------------------------------------------------------------------
-- 5) 核对 3：每年 2 月应有春节假期（天数随春节日期浮动，只要求 > 0）
-- ---------------------------------------------------------------------------
SELECT y.`年份`,
       COUNT(n.`id`) AS 二月非工作日天数,
       CASE WHEN COUNT(n.`id`) > 0 THEN '正常' ELSE '★缺失' END AS 判定
FROM (SELECT 2025 AS `年份` UNION SELECT 2026 UNION SELECT 2027) y
LEFT JOIN `t_non_working_day` n
       ON YEAR(n.`non_working_time`) = y.`年份` AND MONTH(n.`non_working_time`) = 2
GROUP BY y.`年份` ORDER BY 年份;
